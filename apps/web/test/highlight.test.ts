import { describe, expect, it } from 'vitest'
import { highlightSnippet } from '../src/search/highlight.ts'
import { significantWords } from '../src/search/words.ts'

const marked = (snippet: string, query: string) =>
  highlightSnippet(snippet, significantWords(query))
    .map((part) => (part.match ? `[${part.text}]` : part.text))
    .join('')

describe('highlightSnippet', () => {
  it.each([
    [
      'Иван Феодотов Коваленко и Андрей Коваленко жена',
      'коваленко',
      'Иван Феодотов [Коваленко] и Андрей [Коваленко] жена',
    ],
    [
      'Деревни Михайловский Борщаговки крестьяне.',
      'Борщаговки',
      'Деревни Михайловский [Борщаговки] крестьяне.',
    ],
    ['Деревни Михайловский Борщаговки', 'Борщагов', 'Деревни Михайловский Борщаговки'],
    ['Іван Іванченко з Іванівки', 'Іван', '[Іван] Іванченко з Іванівки'],
    ['Петров-Іванченко', 'Іван', 'Петров-Іванченко'],
    ['Іван Коваленко', 'Іван Коваленко', '[Іван] [Коваленко]'],
    ['Коваленко', 'Коваленка', 'Коваленко'],
    ['Сирейской бофузановни', 'Коваленко', 'Сирейской бофузановни'],
    ['Коваленко-Петров жив', 'Петров', '[Коваленко-Петров] жив'],
    ['Коваленко-Петров жив', 'Коваленко-Петров', '[Коваленко-Петров] жив'],
    ['', 'Коваленко', ''],
    ['М’ячин записано', 'М‘ячин', '[М’ячин] записано'],
    ['Ковале́нко записано', 'Коваленко', '[Ковале́нко] записано'],
    ['Йосип Коваль'.normalize('NFD'), 'Йосип', `[${'Йосип'.normalize('NFD')}] Коваль`],
    ['від Коваленка від', 'від Коваленка', 'від [Коваленка] від'],
    ['Іван, 1905 р.', 'Іван 1905', '[Іван], 1905 р.'],
    ['‘Коваленко’ записано', 'Коваленко', '‘[Коваленко]’ записано'],
    ["'Коваленко' записано", 'Коваленко', "'[Коваленко]' записано"],
    ['Коваленко- Петров', 'Коваленко', '[Коваленко]- Петров'],
    ['-Коваленко', 'Коваленко', '-[Коваленко]'],
  ])('marks in «%s» the words starting with «%s»', (snippet, query, expected) => {
    expect(marked(snippet, query)).toBe(expected)
  })

  it('keeps the whole text when there is nothing to mark', () => {
    expect(highlightSnippet('Села Борщаговки', [])).toEqual([
      { text: 'Села Борщаговки', match: false },
    ])
  })
})
